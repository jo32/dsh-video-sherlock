export type Translate = (key: CopyKey, values?: Readonly<Record<string, string | number>>) => string

export function normalizeUiLocale(value: unknown): UiLocale | undefined {
  if (typeof value !== 'string') return undefined
  const primary = value.trim().toLowerCase().split('-')[0]
  return UI_LOCALES.find(locale => locale === primary)
}

export function resolveUiLocale(explicit: unknown, requested: readonly string[] = []): UiLocale {
  return normalizeUiLocale(explicit) ?? requested.map(normalizeUiLocale).find((locale): locale is UiLocale => locale !== undefined) ?? 'en'
}

export function createTranslator(locale: UiLocale): Translate {
  const dictionary: Record<CopyKey, string> = locale === 'zh' ? zh : en
  return (key, values = {}) => dictionary[key].replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) => String(values[name] ?? match))
}
